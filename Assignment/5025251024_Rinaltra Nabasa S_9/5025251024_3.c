#include <stdio.h>

/*
 * Recursive mathematical function defined as:
 * f(x) = 0             if x <= 0
 * f(x) = f(x - 1) + 2  otherwise
 */
int f(int x) {
    if (x <= 0) {
        return 0;
    } else {
        return f(x - 1) + 2;
    }
}

int main() {
    printf("====================================================\n");
    printf("  PROGRAM 3: RECURSIVE FUNCTION DEFINITION          \n");
    printf("  Name: Rinaltra Nabasa Simanungkalit | NRP: 5025251024\n");
    printf("====================================================\n\n");

    printf("Recursive Definition:\n");
    printf("  f(x) = 0             if x <= 0\n");
    printf("  f(x) = f(x - 1) + 2  otherwise\n\n");

    printf("Table of Values for x in [-3, 10]:\n");
    printf("---------------------------------\n");
    printf("    x  |  f(x)  |  Calculation / Property\n");
    printf("---------------------------------\n");

    for (int x = -3; x <= 10; x++) {
        if (x <= 0) {
            printf("  %3d  |   %2d   |  Base case (x <= 0)\n", x, f(x));
        } else {
            printf("  %3d  |   %2d   |  f(%d) + 2 = 2 * %d\n", x, f(x), x - 1, x);
        }
    }
    printf("---------------------------------\n\n");

    printf("Question: What set of numbers is generated by this definition?\n");
    printf("Answer:\n");
    printf("  For any non-positive integer (x <= 0), f(x) = 0.\n");
    printf("  For any positive integer (x > 0), by induction:\n");
    printf("    f(1) = 2\n");
    printf("    f(2) = 4\n");
    printf("    f(3) = 6\n");
    printf("    f(x) = 2 * x\n");
    printf("  Therefore, the set of numbers generated by this definition is\n");
    printf("  the set of all non-negative even integers:\n");
    printf("    { 0, 2, 4, 6, 8, 10, ... } = { 2k | k >= 0, k in Z }\n");

    return 0;
}
