#include <stdio.h>

int main()
{
    int n;
    scanf("%d", &n);
    int arr[n];
    for (int i = 0; i < n; i++)
    {
        scanf("%d", arr[n   ]);
    }
    int x;
    scanf("%d", &x);
    int count = 0;

    for(int i = 0; i < arr[n]; i++)
    {
        if (x == arr[n])
        {
            count = count + 1;
        }
    }

    return 0;
}
